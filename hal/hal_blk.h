/* hal/hal_blk.h — блочное устройство: диск, который переживает перезагрузку.
 *
 * Единый интерфейс для любого хранилища: virtio-blk под QEMU (сейчас),
 * SDHCI/eMMC на телефоне (дальше). Всё, что выше этого слоя — файловая
 * система, — не знает, что именно под ней лежит.
 *
 * Адресация — секторами по 512 байт (HAL_BLK_SECTOR). Адреса буферов могут
 * быть любыми, выравнивание не требуется: драйвер сам копирует данные
 * через свой выровненный буфер. Все вызовы синхронные: вернулись — значит,
 * операция завершена (прерываний у нас нет, ожидание — опросом).
 *
 * Платформы без драйвера получают слабые заглушки (hal/hal_blk_stub.c):
 * hal_blk_init() там возвращает 0, и система работает как раньше —
 * целиком в ОЗУ.
 */
#ifndef PROSHIVKAOS_HAL_BLK_H
#define PROSHIVKAOS_HAL_BLK_H

#include <stdint.h>
#include <stddef.h>

#define HAL_BLK_SECTOR 512u

/* Найти и поднять диск. 1 — диск есть и готов, 0 — нет. Повторный вызов
 * безопасен и ничего не пересоздаёт. */
int      hal_blk_init(void);

/* Размер диска в секторах; 0, если диска нет. */
uint64_t hal_blk_sectors(void);

/* Читать/писать count секторов начиная с lba. 0 — успех, -1 — ошибка
 * (нет диска, выход за границу, сбой устройства, таймаут). */
int      hal_blk_read (uint64_t lba, uint32_t count, void *buf);
int      hal_blk_write(uint64_t lba, uint32_t count, const void *buf);

/* Барьер: всё записанное ДО вызова гарантированно дошло до носителя, а не
 * осело в кэше устройства. 0 — успех. Без диска возвращает -1. */
int      hal_blk_flush(void);

#endif
